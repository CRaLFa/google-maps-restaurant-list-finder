def full(city):
    """市名を「都道府県 + 市」にする。東京都のように都道府県自身ならそのまま。"""
    return city if city in PREFECTURES else city_pref[city] + city


# エリア名 -> 3 列目に入れる所在地。区は同名が市をまたぐので市とセットで引く。
ward_loc = {}
for city, wards in WARDS.items():
    for w in wards:
        # 旧形式 (都道府県なし) と新形式の両方を受け付けて移行できるようにする。
        for alias in {"", city, full(city)}:
            ward_loc[(w, alias)] = full(city)
ward_names = {w for ws in WARDS.values() for w in ws}

district_loc = {}
for (city, ward), areas in DISTRICTS.items():
    loc = full(city) if city == ward else full(city) + ward
    for a in areas:
        district_loc[a] = loc

city_loc = {c: p for p, cs in CITIES.items() for c in cs}
city_loc.update({a: p for p, areas in METRO.items() for a in areas})
assert not (set(district_loc) & set(city_loc)), "繁華街と市の指定が重複している"

with open(OUT, encoding="utf-8") as f:
    before = [ln.rstrip("\n") for ln in f if ln.strip()]

after = []
touched = set()
for ln in before:
    cols = (ln.split("\t") + ["", ""])[:3]
    area = cols[0].rsplit(": ", 1)[0]
    if area in ward_names:
        loc = ward_loc.get((area, cols[2]))
        if loc is None:
            sys.exit(f"区の市名が未設定か不正: {ln!r}")
    else:
        loc = district_loc.get(area) or city_loc.get(area)
    if loc:
        # 旧形式は新形式の末尾に一致する (名古屋市 -> 愛知県名古屋市) ので移行を許す。
        if cols[2] and cols[2] != loc and not loc.endswith(cols[2]):
            sys.exit(f"3 列目が既に別の値になっている: {ln!r} (期待 {loc})")
        cols[2] = loc
        touched.add(area)
    after.append("\t".join(cols))

if len(before) != len(after):
    sys.exit("行数が変わっている。中止する。")
if sorted(tuple(r.split("\t")[:2]) for r in before) != \
   sorted(tuple(r.split("\t")[:2]) for r in after):
    sys.exit("1 列目または 2 列目が変わってしまっている。中止する。")
unused = (set(district_loc) | set(city_loc)) - touched
if unused:
    sys.exit(f"TSV に存在しないエリアを指定している: {sorted(unused)}")
bad = {r.split("\t")[2] for r in after
       if r.split("\t")[2] and not r.split("\t")[2].startswith(PREFECTURES)}
if bad:
    sys.exit(f"都道府県から始まっていない所在地がある: {sorted(bad)}")

after.sort()
with open(OUT, "w", encoding="utf-8") as f:
    f.write("\n".join(after) + "\n")

changed = sum(1 for a, b in zip(sorted(before), sorted(after)) if a != b)
print(f"所在地をセットしたエリア: {len(touched)} 個 / 更新行数: {changed}")
