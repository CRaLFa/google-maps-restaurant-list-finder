def full(city):
    """市名を「都道府県 + 市」にする。東京都のように都道府県自身ならそのまま。"""
    return city if city in PREFECTURES else city_pref[city] + city


ward_names = {w for ws in WARDS.values() for w in ws}

# 同名の区は所在地の手掛かりが無いと一意に決まらない。
AMBIGUOUS = {w for w in ward_names
             if len({full(c) for c, ws in WARDS.items() if w in ws}) > 1}

# エリア名 -> 所在地。区は同名が市をまたぐので市とセットで引く。
ward_loc = {}
for _city, _wards in WARDS.items():
    for _w in _wards:
        # 旧形式 (都道府県なし) と新形式の両方を受け付けて移行できるようにする。
        aliases = {_city, full(_city)}
        # 曖昧な区に空の別名を張ると市どうしで上書きし合って誤った所在地になる。
        # 手掛かり無しでは引けないようにしておく。
        if _w not in AMBIGUOUS:
            aliases.add("")
        for _alias in aliases:
            ward_loc[(_w, _alias)] = full(_city)

district_loc = {}
for (_city, _ward), _areas in DISTRICTS.items():
    _loc = full(_city) if _city == _ward else full(_city) + _ward
    for _a in _areas:
        district_loc[_a] = _loc

city_loc = {c: p for p, cs in CITIES.items() for c in cs}
city_loc.update({a: p for p, areas in METRO.items() for a in areas})
assert not (set(district_loc) & set(city_loc)), "繁華街と市の指定が重複している"


def resolve(area, hint=""):
    """エリア名から所在地を返す。決められなければ None。

    同名の区 (中区・北区等) は市をまたぐため、hint に既知の所在地を渡さないと決まらない。
    端末の UI 上は同名の区を見分けられないので、収集スクリプトからは hint 無しで呼ばれる。
    その場合 None が返るので、呼び出し側は WARDS を更新するよう促して飛ばすこと。
    """
    if area in ward_names:
        return ward_loc.get((area, hint))
    return district_loc.get(area) or city_loc.get(area)


